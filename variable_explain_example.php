// variable in PHP is a container for storing data values. ex: name, age, price, isActive
// variables rules in PHP:
// 1. A variable starts with the $ sign, followed by the name of the variable. ex: $name, $age, $price, $isActive
// 2. A variable name must start with a letter or the underscore character. ex: $name, $_age
// 3. A variable name cannot start with a number. ex: $1name, $2age
// 4. A variable name can only contain alpha-numeric characters and underscores (A-z, 0-9, and _ ). ex: $name_1, $age_2


